#Requires -Modules Logging

# Generate the dedicated server config Scripts/Dedicated/<SSAM_CONFIG>/ from the SSAM_* settings:
#   init.ini         server settings (port, mode, players, passwords ...)
#   <n>_begin.ini    one per SSAM_LEVELS entry; sets ded_strLevel for round n
#   <n>_end.ini      announces the next round
# DedicatedServer.exe plays the rounds in order and starts over at 1 after the last one.
#
# The folder is written through the merged view, so it lands in Overlay/. It is regenerated on every
# start as long as it holds the .lancommander marker; a config folder without the marker (your own,
# or the stock DefaultCoop ...) is left alone.

$config = if ($Env:SSAM_CONFIG) { $Env:SSAM_CONFIG } else { 'LANCommander' }
$dir    = Join-Path $Env:SERVER_ROOT "Scripts/Dedicated/$config"
$marker = Join-Path $dir '.lancommander'

if ((Test-Path -Path $dir) -and -not (Test-Path -Path $marker)) {
    Write-Log "Scripts/Dedicated/$config is not managed by this image; using it as is"
    return
}

# Serious Engine string literal
function Format-String([string] $Value) {
    '"' + $Value.Replace('\', '\\').Replace('"', '\"') + '"'
}

function Format-Bool([string] $Value) {
    if ($Value -in @('true', '1', 'yes', 'on')) { '1' } else { '0' }
}

function Format-Level([string] $Level) {
    $path = $Level.Trim().Replace('/', '\')
    if ($path -notmatch '\\') { $path = "Levels\$path" }
    if ($path -notmatch '\.wld$') { $path = "$path.wld" }
    $path
}

$modes = @{ 'coop' = 0; 'cooperative' = 0; 'scorematch' = 1; 'fragmatch' = 2; 'deathmatch' = 2 }
$mode  = "$Env:SSAM_GAME_MODE".ToLower()
if ($modes.ContainsKey($mode)) {
    $mode = $modes[$mode]
} elseif ($mode -notmatch '^[0-2]$') {
    throw "Unknown SSAM_GAME_MODE '$Env:SSAM_GAME_MODE' (coop, scorematch or fragmatch)"
}

$difficulties = @{ 'tourist' = -1; 'easy' = 0; 'normal' = 1; 'hard' = 2; 'serious' = 3 }
$difficulty   = "$Env:SSAM_DIFFICULTY".ToLower()
if ($difficulties.ContainsKey($difficulty)) {
    $difficulty = $difficulties[$difficulty]
} elseif ($difficulty -and $difficulty -notmatch '^-?[0-3]$') {
    throw "Unknown SSAM_DIFFICULTY '$Env:SSAM_DIFFICULTY' (tourist, easy, normal, hard or serious)"
}

$levels = @("$Env:SSAM_LEVELS" -split '[,;]' | Where-Object { $_.Trim() } | ForEach-Object { Format-Level $_ })
if (-not $levels) { throw 'SSAM_LEVELS is empty' }

foreach ($level in $levels) {
    # Levels can also come from .gro packs (mods), so a missing file is only a warning
    if (-not (Test-Path -Path (Join-Path $Env:SERVER_ROOT $level.Replace('\', '/')))) {
        Write-Log -Level Warning "Level $level not found as a file; it must be in a .gro pack"
    }
}

# name, value, formatter
$settings = @(
    @('net_iPort',               $Env:SSAM_PORT,              $null),
    @('gam_strSessionName',      $Env:SSAM_SESSION_NAME,      'string'),
    @('gam_iStartMode',          "$mode",                     $null),
    @('gam_iStartDifficulty',    "$difficulty",               $null),
    @('gam_ctMaxPlayers',        $Env:SSAM_MAX_PLAYERS,       $null),
    @('gam_bWaitAllPlayers',     $Env:SSAM_WAIT_ALL_PLAYERS,  'bool'),
    @('gam_iCredits',            $Env:SSAM_CREDITS,           $null),
    @('gam_bWeaponsStay',        $Env:SSAM_WEAPONS_STAY,      'bool'),
    @('gam_bFriendlyFire',       $Env:SSAM_FRIENDLY_FIRE,     'bool'),
    @('gam_iTimeLimit',          $Env:SSAM_TIME_LIMIT,        $null),
    @('gam_iFragLimit',          $Env:SSAM_FRAG_LIMIT,        $null),
    @('gam_iScoreLimit',         $Env:SSAM_SCORE_LIMIT,       $null),
    @('net_strConnectPassword',  $Env:SSAM_PASSWORD,          'string'),
    @('net_strAdminPassword',    $Env:SSAM_ADMIN_PASSWORD,    'string'),
    @('ded_tmTimeout',           $Env:SSAM_LEVEL_TIMEOUT,     $null),
    @('ser_bWaitFirstPlayer',    $Env:SSAM_WAIT_FIRST_PLAYER, 'bool'),
    @('ser_strMOTD',             $Env:SSAM_MOTD,              'string'),
    @('ser_bHeartbeatGameSpy',   $Env:SSAM_GAMESPY_HEARTBEAT, 'bool')
)

$init = [System.Collections.Generic.List[string]]::new()
$init.Add('// Generated by the LANCommander image from the SSAM_* settings on every start.')
$init.Add('// Remove .lancommander from this folder to keep your own edits.')
$init.Add('')

foreach ($s in $settings) {
    if (-not $s[1]) { continue }
    $value = switch ($s[2]) {
        'string' { Format-String $s[1] }
        'bool'   { Format-Bool $s[1] }
        default  { $s[1] }
    }
    $init.Add("$($s[0]) = $value;")
}

$init.Add("ded_strLevel = $(Format-String $levels[0]);")

if ($Env:SSAM_EXTRA_SETTINGS) {
    $init.Add('')
    $init.Add('// SSAM_EXTRA_SETTINGS')
    $init.Add($Env:SSAM_EXTRA_SETTINGS)
}

New-Item -ItemType Directory -Path $dir -Force | Out-Null
Get-ChildItem -Path $dir -File | Remove-Item -Force

$crlf = "`r`n"
[System.IO.File]::WriteAllText((Join-Path $dir 'init.ini'), ($init -join $crlf) + $crlf)

for ($i = 0; $i -lt $levels.Count; $i++) {
    $round = $i + 1
    $name  = [System.IO.Path]::GetFileNameWithoutExtension($levels[$i].Replace('\', '/'))
    $begin = @(
        "ded_strLevel = $(Format-String $levels[$i]);",
        "$(Format-String "-------------------- Round $($round): $name --------------------");"
    )
    $end = @(
        'Say("The level is finished, next level in " + (CTString)(INDEX)ded_tmTimeout + " seconds");'
    )
    [System.IO.File]::WriteAllText((Join-Path $dir "$($round)_begin.ini"), ($begin -join $crlf) + $crlf)
    [System.IO.File]::WriteAllText((Join-Path $dir "$($round)_end.ini"), ($end -join $crlf) + $crlf)
}

Set-Content -Path $marker -Value 'Regenerated from SSAM_* on every start. Delete this file to keep your own edits.'
chown -R "$($Env:UID):$($Env:GID)" $dir

Write-Log "Generated Scripts/Dedicated/$config ($($levels.Count) level(s), mode $mode)"
